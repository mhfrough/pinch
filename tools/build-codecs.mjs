#!/usr/bin/env node
// Builds Pinch's image engine:
//   pinch/engine.js                 classic script, window.Pinch (from src/engine/main.js)
//   pinch/codecs/worker.js          module worker: pipeline + every codec's JS glue (small)
//   pinch/codecs/*.wasm             every .wasm the worker references (fetched lazily, one per codec)
//   pinch/codecs/heif.js            HEIC decoder (libheif, LGPL-3.0, wasm embedded), its own file
//   pinch/codecs/fallback-codecs.js classic script with pure-JS codecs for the no-WebAssembly path
//   pinch/codecs/licenses/, pinch/codecs/README.md
//
// Usage:  node pinch/tools/build-codecs.mjs
// Dependencies are read from PINCH_DEPS (a node_modules folder), default ../.devcache/jsq/node_modules
// next to the pinch folder. They need: esbuild @jsquash/{jpeg,webp,avif,png,oxipng,resize}
// wasm-feature-detect gifenc upng-js pako heic-to.

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');                        // pinch/
const deps = path.resolve(process.env.PINCH_DEPS || path.join(root, '..', '.devcache', 'jsq', 'node_modules'));
const out = path.join(root, 'codecs');
const require = createRequire(path.join(deps, 'noop.js'));
const esbuild = require('esbuild');

const pkgVersion = (name) => JSON.parse(fs.readFileSync(path.join(deps, name, 'package.json'), 'utf8')).version;

// ---------------------------------------------------------------- clean
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'licenses'), { recursive: true });

const NODE_BUILTINS = ['fs', 'path', 'crypto', 'module', 'url', 'worker_threads', 'perf_hooks', 'os', 'util', 'ws'];
const libheifPath = path.join(deps, 'heic-to', 'src', 'lib', 'libheif-without-unsafe-eval.js');
const aliasPlugin = (map) => ({
  name: 'pinch-alias',
  setup(b) {
    for (const [name, file] of Object.entries(map)) {
      const re = new RegExp('^' + name.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&') + '$');
      b.onResolve({ filter: re }, () => ({ path: file }));
    }
  },
});
const ENGINE_BANNER = `/* Pinch image engine v2 - window.Pinch
 * GENERATED by tools/build-codecs.mjs from src/engine/ and src/shared/: edit those, then rebuild.
 * Everything runs in this browser; nothing is uploaded. Codecs load from ./codecs/ (same origin).
 *
 * Pinch.ready    Promise<{ wasm, webpNative, avifNative, workers, encode: {fmt: bool}, heic }>
 *                webpNative/avifNative = the browser can display that format (for previews);
 *                encode = formats process() can write here (all true when wasm is true).
 * Pinch.warmed   Promise<true> once every codec is fetched + compiled in the background (offline-ready).
 * Pinch.FORMATS  { jpeg|png|webp|avif|gif|bmp|ico: { label, ext, mime, lossy, alpha } }
 * Pinch.inspect(file)  -> { width, height, format, alpha, bytes, colours: 'photo'|'graphic', thumbUrl, animated }
 * Pinch.process(file, settings, { signal, onProgress }) -> Result
 *   settings = { format: 'auto'|'same'|fmt, quality 1-100, lossless, pngColors 0|256|128|64|32|16,
 *     resize: { mode: 'none'|'percent'|'fit'|'width'|'height', percent, width, height },
 *     upscale: { factor 1-4, method: 'smooth'|'sharp'|'pixel' }, target (bytes, 0 = off),
 *     background '#ffffff', stripMetadata (default true) }
 *   Result = { blob, url, width, height, format, quality, colors, bytes, notes[], kept, ms }
 *   onProgress({ stage: 'load'|'decode'|'resize'|'encode'|'search'|'compare', progress 0-1, message })
 *   Rejects with an Error whose message is friendly; a cancel rejects with name 'AbortError'.
 *   result.url is revoked when the same file is processed again or released.
 * Pinch.compare(file, settings, opts) -> { jpeg, webp, png, avif } each { bytes, ms } | { error } | { skipped }
 * Pinch.cancel(file) / Pinch.release(file) / Pinch.preload(format)
 * Pinch.zip([{ name, blob }]) -> Blob   Pinch.bytes(n) -> '353 KB'   Pinch.outName(name, format)
 * Force the canvas fallback with window.PinchConfig = { wasm: false } or ?pinch-nowasm.
 * Disable the idle warm-up with window.PinchConfig = { warm: false }.
 */`;
const common = { bundle: true, platform: 'browser', mainFields: ['module', 'main'], nodePaths: [deps], logLevel: 'warning', legalComments: 'none' };

// ---------------------------------------------------------------- worker
// One self-contained module (no static or relative imports) so the engine can start workers from a
// Blob URL and keep working offline. The codecs' heavy parts, the .wasm files, are fetched lazily.
// import.meta.url in the codec glue is redirected to self.__pinchBase (the codecs/ folder URL).
const workerBuild = await esbuild.build({
  ...common,
  entryPoints: { worker: path.join(root, 'src', 'worker', 'worker.js') },
  outdir: out,
  format: 'esm',
  splitting: false,
  minify: true,
  target: ['es2020'],
  external: NODE_BUILTINS,
  define: { 'import.meta.url': 'self.__pinchBase' },
  banner: { js: 'self.__pinchBase=(function(n){var i=n.indexOf("|");return i>=0?n.slice(i+1):String(self.location.href).replace(/[^/]*$/,"")})(self.name||"");' },
  plugins: [aliasPlugin({ pako: path.join(root, 'src', 'worker', 'pako-stub.js') })],
  metafile: true,
  logOverride: { 'assign-to-import-meta': 'silent', 'empty-import-meta': 'silent', 'assign-to-define': 'silent' },
});

// ---------------------------------------------------------------- HEIC decoder (LGPL-3.0), separate file
await esbuild.build({
  ...common,
  entryPoints: { heif: libheifPath },
  outdir: out,
  format: 'esm',
  minify: true,
  target: ['es2020'],
  external: NODE_BUILTINS,
  banner: { js: '/* libheif 1.23.6 + libde265 1.0.16, LGPL-3.0, built by heic-to (https://github.com/hoppergee/heic-to). See licenses/. */' },
  logOverride: { 'empty-import-meta': 'silent' },
});

// ---------------------------------------------------------------- fallback pure-JS codecs (classic script)
await esbuild.build({
  ...common,
  entryPoints: [path.join(root, 'src', 'engine', 'fallback-codecs.js')],
  outfile: path.join(out, 'fallback-codecs.js'),
  format: 'iife',
  minify: true,
  target: ['es2017'],
});

// ---------------------------------------------------------------- engine.js (classic script)
await esbuild.build({
  ...common,
  entryPoints: [path.join(root, 'src', 'engine', 'main.js')],
  outfile: path.join(root, 'engine.js'),
  format: 'iife',
  minify: false,
  target: ['es2017'],
  banner: { js: ENGINE_BANNER },
});

// ---------------------------------------------------------------- copy referenced wasm
const wasmIndex = new Map();
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.wasm')) { if (!wasmIndex.has(e.name)) wasmIndex.set(e.name, p); }
  }
})(path.join(deps, '@jsquash'));

const referenced = new Map(); // wasm -> [chunks]
for (const f of fs.readdirSync(out)) {
  if (!f.endsWith('.js')) continue;
  const src = fs.readFileSync(path.join(out, f), 'utf8');
  for (const m of src.matchAll(/new URL\(\s*["'`]([\w.-]+\.wasm)["'`]\s*,/g)) {
    if (!referenced.has(m[1])) referenced.set(m[1], []);
    referenced.get(m[1]).push(f);
  }
}
for (const [name] of referenced) {
  const from = wasmIndex.get(name);
  if (!from) throw new Error('Referenced wasm not found in dependencies: ' + name);
  fs.copyFileSync(from, path.join(out, name));
}
if (referenced.has('avif_enc_mt.wasm')) throw new Error('The multi-threaded AVIF build leaked into the bundle');

// ---------------------------------------------------------------- licences
const LICENSES = [
  ['@jsquash/jpeg/LICENSE', 'jSquash-Apache-2.0.txt'],
  ['@jsquash/jpeg/codec/LICENSE.codec.md', 'mozjpeg-libjpeg-turbo.md'],
  ['@jsquash/webp/codec/LICENSE.codec.md', 'libwebp-BSD.md'],
  ['@jsquash/oxipng/codec/LICENSE.codec.md', 'oxipng-MIT.md'],
  ['@jsquash/resize/lib/resize/LICENSE.codec.md', 'resize-MIT.md'],
  ['@jsquash/resize/lib/hqx/LICENSE.codec.md', 'hqx-Apache-2.0.md'],
  ['heic-to/LICENSE', 'heic-to-libheif-LGPL-3.0.txt'],
  ['upng-js/LICENSE', 'upng-js-MIT.txt'],
  ['gifenc/LICENSE.md', 'gifenc-MIT.md'],
  ['pako/LICENSE', 'pako-MIT.txt'],
];
for (const [from, to] of LICENSES) fs.copyFileSync(path.join(deps, from), path.join(out, 'licenses', to));
fs.writeFileSync(path.join(out, 'licenses', 'libavif-libaom-BSD-2-Clause.txt'), AVIF_LICENSE());

// ---------------------------------------------------------------- README with sizes
const kb = (n) => (n / 1024).toFixed(n < 10240 ? 1 : 0) + ' KB';
const sizeOf = (f) => fs.statSync(path.join(out, f)).size;
const WASM_WHAT = {
  'mozjpeg_enc.wasm': 'MozJPEG encoder', 'webp_enc_simd.wasm': 'WebP encoder (SIMD browsers)', 'webp_enc.wasm': 'WebP encoder (no SIMD)',
  'avif_enc.wasm': 'AVIF encoder (libavif + libaom, single thread)', 'avif_dec.wasm': 'AVIF decoder (only if the browser cannot decode AVIF)',
  'webp_dec.wasm': 'WebP decoder (only if the browser cannot decode WebP)', 'squoosh_oxipng_bg.wasm': 'OxiPNG (PNG optimiser)',
  'squoosh_resize_bg.wasm': 'Lanczos3 resizer', 'squooshhqx_bg.wasm': 'hqx pixel-art upscaler',
};
const rows = [['worker.js', 'worker: pipeline, cache, all codec JS glue, quantiser, GIF/BMP/ICO writers, Magic Kernel Sharp (loaded when the engine starts)']];
for (const w of [...referenced.keys()].sort((a, b) => sizeOf(b) - sizeOf(a))) rows.push([w, WASM_WHAT[w] || w]);
rows.push(['heif.js', 'HEIC decoder (libheif + libde265, LGPL-3.0, wasm embedded); only when the browser cannot open a HEIC file']);
rows.push(['fallback-codecs.js', 'pure-JS PNG/GIF codecs for the canvas fallback (no module workers / WebAssembly); classic script']);
const versions = ['@jsquash/jpeg', '@jsquash/webp', '@jsquash/avif', '@jsquash/oxipng', '@jsquash/resize', '@jsquash/png', 'wasm-feature-detect', 'gifenc', 'upng-js', 'pako', 'heic-to', 'esbuild']
  .map((n) => '| ' + n + ' | ' + pkgVersion(n) + ' |').join('\n');

fs.writeFileSync(path.join(out, 'README.md'), `# Pinch codecs (generated)

Built by \`node tools/build-codecs.mjs\` from \`src/\`. Do not edit files here by hand.
Everything is same-origin; nothing is fetched from a CDN. \`worker.js\` is the module worker that
\`engine.js\` starts (from a Blob URL of its source, so restarts work offline).

## Files

| File | What | Size |
|---|---|---|
${rows.map(([f, what]) => `| ${f} | ${what} | ${kb(sizeOf(f))} |`).join('\n')}

Every .wasm (and heif.js) is fetched the first time it is needed. Once the page is idle, the engine
also warms them all in the background (AVIF encoder last; skipped on Save-Data except the small ones)
and shares the compiled WebAssembly modules with every worker, so Pinch keeps working offline.

The multi-threaded AVIF encoder and multi-threaded OxiPNG are deliberately not included:
they need SharedArrayBuffer (COOP/COEP headers), which GitHub Pages cannot send.

## Versions

| Package | Version |
|---|---|
${versions}

Codec versions inside jSquash: MozJPEG 4 (libjpeg-turbo), libwebp, libavif + libaom, OxiPNG,
resize (PistonDevelopers), hqx (wasmboy-rs). HEIC: libheif 1.23.6 with libde265 1.0.16,
as built by heic-to (no unsafe-eval build).

## Licences

Files are in \`licenses/\`.

- jSquash wrappers and Squoosh glue: Apache-2.0
- MozJPEG / libjpeg-turbo: IJG + BSD-3-Clause + zlib
- libwebp: BSD-3-Clause
- libavif, libaom: BSD-2-Clause (plus the AOM patent licence)
- OxiPNG, resize: MIT; hqx: Apache-2.0. Magic Kernel Sharp 2021 is implemented in Pinch's own JS
  (src/shared/resample.js) from John Costella's published kernel (https://johncostella.com/magic/)
- UPNG.js (palette quantiser), gifenc, pako: MIT
- heic-to / libheif / libde265: **LGPL-3.0**. The HEIC decoder is kept as its own file,
  \`heif.js\`, loaded only when a HEIC/HEIF file is opened and the browser cannot decode it
  natively (or during the idle warm-up). It is unmodified and can be replaced with any compatible
  build. Source: https://github.com/hoppergee/heic-to and https://github.com/strukturag/libheif.
`);

